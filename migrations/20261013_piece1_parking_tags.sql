GRANT EXECUTE ON FUNCTION public.normalize_tag_number(TEXT) TO service_role;

-- ── read scope ──────────────────────────────────────────────────────
-- Manager / leasing agent: tags at a property in their assignment.
-- Comparison is lower(trim(...)) on BOTH sides on the column side,
-- which a client .eq()/.ilike() cannot express.
DROP POLICY IF EXISTS vpt_manager_select ON public.vehicle_parking_tags;
CREATE POLICY vpt_manager_select ON public.vehicle_parking_tags
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
        FROM public.user_roles ur
        JOIN public.properties p ON p.id = vehicle_parking_tags.property_id
       WHERE lower(trim(ur.email)) = lower(trim(COALESCE(auth.jwt() ->> 'email', '')))
         AND ur.is_active
         AND ur.role IN ('manager', 'leasing_agent')
         AND EXISTS (
           SELECT 1 FROM unnest(ur.property) AS a(nm)
            WHERE lower(trim(a.nm)) = lower(trim(p.name))
         )
    )
  );

-- Company admin / super admin: everything in their company.
DROP POLICY IF EXISTS vpt_company_admin_select ON public.vehicle_parking_tags;
CREATE POLICY vpt_company_admin_select ON public.vehicle_parking_tags
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1
        FROM public.user_roles ur
        JOIN public.properties p ON p.id = vehicle_parking_tags.property_id
       WHERE lower(trim(ur.email)) = lower(trim(COALESCE(auth.jwt() ->> 'email', '')))
         AND ur.is_active
         AND ( ur.role = 'admin'
            OR (ur.role = 'company_admin'
                AND lower(trim(ur.company)) = lower(trim(p.company))) )
    )
  );

-- Resident: READ-ONLY, and only their own vehicle's tag. Ruled.
DROP POLICY IF EXISTS vpt_resident_select_own ON public.vehicle_parking_tags;
CREATE POLICY vpt_resident_select_own ON public.vehicle_parking_tags
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.vehicles v
       WHERE v.id = vehicle_parking_tags.vehicle_id
         AND lower(trim(v.resident_email)) = lower(trim(COALESCE(auth.jwt() ->> 'email', '')))
    )
  );

-- 🔴 No FOR INSERT / UPDATE / DELETE policy exists, and none should.
-- set_vehicle_tag and void_vehicle_tag are SECURITY DEFINER and bypass
-- RLS by design; they are the only write path. Adding a write policy
-- here would silently reopen what moving off vehicles closed.

-- ── authority helper ────────────────────────────────────────────────
-- SECURITY DEFINER is load-bearing: this is called from inside the
-- write RPCs, and also needs to answer for a resident (who has no
-- SELECT on user_roles rows other than their own).
CREATE OR REPLACE FUNCTION public.may_manage_parking_tags_at(p_property_id BIGINT)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
  SELECT EXISTS (
    SELECT 1
      FROM public.user_roles ur
      JOIN public.properties p ON p.id = p_property_id
     WHERE lower(trim(ur.email)) = lower(trim(COALESCE(auth.jwt() ->> 'email', '')))
       AND ur.is_active
       AND (
            ur.role = 'admin'
         OR (ur.role = 'company_admin'
             AND lower(trim(ur.company)) = lower(trim(p.company)))
         OR (ur.role IN ('manager', 'leasing_agent')
             AND EXISTS (SELECT 1 FROM unnest(ur.property) AS a(nm)
                          WHERE lower(trim(a.nm)) = lower(trim(p.name))))
       )
  )
$fn$;

REVOKE ALL ON FUNCTION public.may_manage_parking_tags_at(BIGINT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.may_manage_parking_tags_at(BIGINT) FROM anon;
GRANT EXECUTE ON FUNCTION public.may_manage_parking_tags_at(BIGINT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.may_manage_parking_tags_at(BIGINT) TO service_role;

COMMENT ON FUNCTION public.may_manage_parking_tags_at(BIGINT) IS
  'May the current caller issue or void a parking tag at this property? Manager and leasing_agent by property assignment, company_admin by company, admin anywhere. SECURITY DEFINER because it is called from inside the write RPCs and must read user_roles rows the caller cannot select directly. A caller with no JWT gets FALSE — unlike the properties guard, there is no service-role passthrough here, because every legitimate writer is a logged-in person.';

-- ── the only write path: issue / re-issue / clear ───────────────────
-- 🔴 Returns jsonb for EVERY expected outcome and raises for none of
-- them. The UI must never have to render a Postgres string: a refusal
-- carries a code the client maps to plain copy. (See the raw-DB-errors
-- sweep — this is the shape that sweep is heading toward.)
CREATE OR REPLACE FUNCTION public.set_vehicle_tag(
  p_vehicle_id BIGINT,
  p_tag        TEXT
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_email   TEXT;
  v_veh     public.vehicles;
  v_prop    public.properties;
  v_tag     TEXT;
  v_prior   public.vehicle_parking_tags;
  v_clash_plate TEXT;
  v_clash_unit  TEXT;
  v_clash_found BOOLEAN;
  v_new_id  BIGINT;
BEGIN
  v_email := lower(trim(COALESCE(auth.jwt() ->> 'email', '')));
  IF v_email = '' THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'not_signed_in');
  END IF;

  SELECT * INTO v_veh FROM public.vehicles WHERE id = p_vehicle_id;
  IF v_veh.id IS NULL THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'vehicle_not_found');
  END IF;

  -- Resolve the property by (company, name), both lower(trim()). NOT by
  -- name alone: names are not unique across companies, and the name is
  -- the renameable, whitespace-carrying key this table deliberately
  -- does not store.
  SELECT * INTO v_prop
    FROM public.properties
   WHERE lower(trim(name))    = lower(trim(COALESCE(v_veh.property, '')))
     AND lower(trim(company)) = lower(trim(COALESCE(v_veh.company, '')));
  IF v_prop.id IS NULL THEN
    -- Absence must not read as success, and must not read as "no tag".
    RETURN jsonb_build_object('ok', FALSE, 'error', 'property_not_resolved',
                              'property', v_veh.property, 'company', v_veh.company);
  END IF;

  IF NOT public.may_manage_parking_tags_at(v_prop.id) THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'not_permitted');
  END IF;

  IF NOT COALESCE(v_prop.parking_tags_enabled, FALSE) THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'parking_tags_not_enabled',
                              'property', v_prop.name);
  END IF;

  v_tag := public.normalize_tag_number(p_tag);

  SELECT * INTO v_prior
    FROM public.vehicle_parking_tags
   WHERE vehicle_id = p_vehicle_id AND voided_at IS NULL;

  -- ── clear: an empty tag voids whatever is held, and is not an error
  IF v_tag IS NULL THEN
    IF v_prior.id IS NULL THEN
      RETURN jsonb_build_object('ok', TRUE, 'action', 'already_no_tag');
    END IF;
    UPDATE public.vehicle_parking_tags
       SET voided_at = now(), voided_by = v_email, voided_reason = 'cleared_by_staff'
     WHERE id = v_prior.id;
    INSERT INTO public.audit_logs (user_email, action, table_name, record_id, old_values, new_values, notes)
    VALUES (v_email, 'clear_vehicle_tag', 'vehicle_parking_tags', v_prior.id,
            jsonb_build_object('tag_number', v_prior.tag_number),
            jsonb_build_object('voided_reason', 'cleared_by_staff'),
            format('Parking tag %s cleared from %s at %s', v_prior.tag_number, v_veh.plate, v_prop.name));
    RETURN jsonb_build_object('ok', TRUE, 'action', 'cleared',
                              'previous_tag_number', v_prior.tag_number);
  END IF;

  -- 🔴 The vehicle must be in the authorized set. A tag on a pending or
  -- declined vehicle would read to enforcement as corroboration of an
  -- authorization that does not exist.
  -- Both predicates, deliberately: 19 rows live today with
  -- is_active=false AND status='active', so neither column alone
  -- answers "is this vehicle authorized".
  IF NOT (COALESCE(v_veh.is_active, FALSE) AND v_veh.status = 'active') THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'vehicle_not_active',
                              'status', v_veh.status, 'is_active', v_veh.is_active);
  END IF;

  IF v_prior.id IS NOT NULL AND v_prior.tag_number = v_tag THEN
    RETURN jsonb_build_object('ok', TRUE, 'action', 'unchanged', 'tag_number', v_tag);
  END IF;

  -- Already live on a DIFFERENT vehicle at this property? Refuse and
  -- name the plate: a manager holding the physical tag needs to know
  -- which car the system thinks has it. They can already see every
  -- plate at their own property, so this discloses nothing new.
  -- 🔴 FOUND, not a field test on a RECORD. A record whose SELECT INTO
  -- matched no row cannot be safely field-accessed, and scalars plus
  -- FOUND say exactly what was observed either way.
  SELECT v.plate, v.unit
    INTO v_clash_plate, v_clash_unit
    FROM public.vehicle_parking_tags t
    JOIN public.vehicles v ON v.id = t.vehicle_id
   WHERE t.property_id = v_prop.id
     AND t.tag_number  = v_tag
     AND t.voided_at IS NULL
     AND t.vehicle_id <> p_vehicle_id;
  v_clash_found := FOUND;
  IF v_clash_found THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'tag_already_assigned',
                              'tag_number', v_tag,
                              'held_by_plate', v_clash_plate,
                              'held_by_unit',  v_clash_unit);
  END IF;

  IF v_prior.id IS NOT NULL THEN
    UPDATE public.vehicle_parking_tags
       SET voided_at = now(), voided_by = v_email, voided_reason = 'reissued'
     WHERE id = v_prior.id;
  END IF;

  INSERT INTO public.vehicle_parking_tags (vehicle_id, property_id, tag_number, assigned_by)
  VALUES (p_vehicle_id, v_prop.id, v_tag, v_email)
  RETURNING id INTO v_new_id;

  INSERT INTO public.audit_logs (user_email, action, table_name, record_id, old_values, new_values, notes)
  VALUES (v_email,
          CASE WHEN v_prior.id IS NULL THEN 'assign_vehicle_tag' ELSE 'reissue_vehicle_tag' END,
          'vehicle_parking_tags', v_new_id,
          CASE WHEN v_prior.id IS NULL THEN NULL
               ELSE jsonb_build_object('tag_number', v_prior.tag_number) END,
          jsonb_build_object('tag_number', v_tag, 'vehicle_id', p_vehicle_id, 'property_id', v_prop.id),
          format('Parking tag %s issued to %s at %s', v_tag, v_veh.plate, v_prop.name));

  RETURN jsonb_build_object('ok', TRUE,
                            'action', CASE WHEN v_prior.id IS NULL THEN 'assigned' ELSE 'reissued' END,
                            'tag_number', v_tag,
                            'previous_tag_number', v_prior.tag_number);
END;
$fn$;

REVOKE ALL ON FUNCTION public.set_vehicle_tag(BIGINT, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.set_vehicle_tag(BIGINT, TEXT) FROM anon;
GRANT EXECUTE ON FUNCTION public.set_vehicle_tag(BIGINT, TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.set_vehicle_tag(BIGINT, TEXT) TO service_role;

COMMENT ON FUNCTION public.set_vehicle_tag(BIGINT, TEXT) IS
  'The ONLY write path for a parking tag. Issues, re-issues (voiding the previous row, keeping it as history) or clears a tag. Refuses: a property with parking_tags_enabled off, a caller without authority there, a vehicle outside the authorized set (is_active AND status=''active'' — both, since rows exist with one true and the other not), and a number already live on another vehicle at that property. Returns jsonb for every expected outcome and raises for none of them, so no caller has to render a Postgres string.';

-- ── manual void ─────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.void_vehicle_tag(
  p_vehicle_id BIGINT,
  p_reason     TEXT,
  p_note       TEXT DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_email TEXT;
  v_row   public.vehicle_parking_tags;
BEGIN
  v_email := lower(trim(COALESCE(auth.jwt() ->> 'email', '')));
  IF v_email = '' THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'not_signed_in');
  END IF;
  IF COALESCE(trim(p_reason), '') = '' THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'reason_required');
  END IF;

  SELECT * INTO v_row
    FROM public.vehicle_parking_tags
   WHERE vehicle_id = p_vehicle_id AND voided_at IS NULL;
  IF v_row.id IS NULL THEN
    RETURN jsonb_build_object('ok', TRUE, 'action', 'already_no_tag');
  END IF;

  IF NOT public.may_manage_parking_tags_at(v_row.property_id) THEN
    RETURN jsonb_build_object('ok', FALSE, 'error', 'not_permitted');
  END IF;

  -- Deliberately NOT gated on parking_tags_enabled: a property whose
  -- switch was turned off still needs its outstanding tags voidable.
  -- Gating the un-do on the same flag as the do would trap rows.
  UPDATE public.vehicle_parking_tags
     SET voided_at = now(), voided_by = v_email,
         voided_reason = trim(p_reason), voided_note = NULLIF(trim(COALESCE(p_note,'')), '')
   WHERE id = v_row.id;

  INSERT INTO public.audit_logs (user_email, action, table_name, record_id, old_values, new_values, notes)
  VALUES (v_email, 'void_vehicle_tag', 'vehicle_parking_tags', v_row.id,
          jsonb_build_object('tag_number', v_row.tag_number),
          jsonb_build_object('voided_reason', trim(p_reason)),
          format('Parking tag %s voided', v_row.tag_number));

  RETURN jsonb_build_object('ok', TRUE, 'action', 'voided', 'tag_number', v_row.tag_number);
END;
$fn$;

REVOKE ALL ON FUNCTION public.void_vehicle_tag(BIGINT, TEXT, TEXT) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.void_vehicle_tag(BIGINT, TEXT, TEXT) FROM anon;
GRANT EXECUTE ON FUNCTION public.void_vehicle_tag(BIGINT, TEXT, TEXT) TO authenticated;
GRANT EXECUTE ON FUNCTION public.void_vehicle_tag(BIGINT, TEXT, TEXT) TO service_role;

-- ── void when the vehicle leaves the authorized set ─────────────────
-- 🔴 A TRIGGER, not a change to deactivate_vehicle. Many paths take a
-- vehicle out of the authorized set: deactivate_vehicle,
-- deactivate_my_vehicle, the add_plate_prohibition cascade, owner_trim,
-- admin_cascade, resident_removed — and a manager's direct PATCH, which
-- is exactly the hole that moved this off vehicles. A trigger is the
-- only choke point that covers all of them, and the required outcome
-- here is a side effect rather than a refusal, so a trigger is right.
--
-- It does NOT un-void on reactivation. A physical tag is collected when
-- a resident moves out; the number must be re-issued deliberately, not
-- resurrected because a row flipped back.
CREATE OR REPLACE FUNCTION public.vehicles_void_parking_tag()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_was_live BOOLEAN := COALESCE(OLD.is_active, FALSE) AND OLD.status = 'active';
  v_is_live  BOOLEAN := COALESCE(NEW.is_active, FALSE) AND NEW.status = 'active';
  v_actor    TEXT := COALESCE(NULLIF(lower(trim(COALESCE(auth.jwt() ->> 'email', ''))), ''), 'system');
  v_moved    BOOLEAN := lower(trim(COALESCE(NEW.property, ''))) IS DISTINCT FROM lower(trim(COALESCE(OLD.property, '')));
BEGIN
  -- Left the authorized set.
  IF v_was_live AND NOT v_is_live THEN
    UPDATE public.vehicle_parking_tags
       SET voided_at     = now(),
           -- The CHECK requires a voided_by; a cron or SQL path has no
           -- JWT, and 'system' is honest about that.
           voided_by     = v_actor,
           voided_reason = 'vehicle_left_authorized_set',
           voided_note   = format('vehicle %s -> is_active=%s status=%s', NEW.id, NEW.is_active, NEW.status)
     WHERE vehicle_id = NEW.id
       AND voided_at IS NULL;
  END IF;

  -- 🔴 Moved to a different property. A physical tag is issued for a
  -- specific lot — the number is unique per property, and enforcement
  -- at the new lot would read a tag the new lot never issued. Voided on
  -- the move, re-issued at the new property if that property has tags
  -- switched on at all. Scoped to tags whose property_id no longer
  -- matches, so a cosmetic rename that leaves the id alone is a no-op.
  IF v_moved THEN
    UPDATE public.vehicle_parking_tags t
       SET voided_at     = now(),
           voided_by     = v_actor,
           voided_reason = 'vehicle_moved_property',
           voided_note   = format('vehicle %s moved %L -> %L', NEW.id, OLD.property, NEW.property)
     WHERE t.vehicle_id = NEW.id
       AND t.voided_at IS NULL
       AND NOT EXISTS (
         SELECT 1 FROM public.properties p
          WHERE p.id = t.property_id
            AND lower(trim(p.name))    = lower(trim(COALESCE(NEW.property, '')))
            AND lower(trim(p.company)) = lower(trim(COALESCE(NEW.company, '')))
       );
  END IF;
  RETURN NULL;   -- AFTER trigger
END;
$fn$;

-- 🔴 A trigger function needs NO caller EXECUTE: the privilege is
-- checked at CREATE TRIGGER time, not when the trigger fires. So this
-- is revoked from PUBLIC and anon and granted to nobody.
REVOKE ALL ON FUNCTION public.vehicles_void_parking_tag() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.vehicles_void_parking_tag() FROM anon;

DROP TRIGGER IF EXISTS vehicles_void_parking_tag_trigger ON public.vehicles;
CREATE TRIGGER vehicles_void_parking_tag_trigger
  AFTER UPDATE OF is_active, status, property, company ON public.vehicles
  FOR EACH ROW
  EXECUTE FUNCTION public.vehicles_void_parking_tag();

COMMENT ON FUNCTION public.vehicles_void_parking_tag() IS
  'Voids a vehicle''s live parking tag when the vehicle leaves the authorized set (is_active AND status=''active'' -> not), or when it MOVES to a different property — a tag is issued for one lot, its number is unique per property, and enforcement at the new lot would otherwise read a tag that lot never issued. A trigger because many paths deactivate a vehicle — the RPCs, the prohibition cascade, and a manager''s direct PATCH — and only a trigger covers all of them. Does NOT un-void on reactivation: a collected physical tag is re-issued deliberately. voided_by falls back to ''system'' for a no-JWT path, which the void-is-complete CHECK requires.';
