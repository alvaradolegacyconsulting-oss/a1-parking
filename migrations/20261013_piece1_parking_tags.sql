-- Ruling: Jose, 2026-10-12. Supersedes "tag_number on vehicles" from
-- the earlier ruling, because manager_update_vehicles is FOR UPDATE TO
-- authenticated for manager with NO column list — proved by execution:
-- a manager PATCHed vehicles.status to 'deactivated' on a test row.
-- A column on vehicles would therefore be directly manager-writable,
-- and "the RPC is the only write path" would need a session-flag guard.
-- A separate table with NO write policy gets that by construction.
--
-- 🔴 NOT "permit". The billing meter is permits; this is a physical
-- tag. Column is tag_number, UI label is "Parking tag #". The plate
-- stays the source of truth — a tag is corroborating evidence, never
-- the authorization itself.
--
-- Keyed on property_id BIGINT, not the property name, mirroring
-- property_plate_prohibitions. The name is renameable and carries
-- whitespace (properties.state = 'tx ' was found the same day), and
-- four tables already reference properties by name to our cost.
--
-- Paired: wip-20261013_piece1_parking_tags_verification.sql
-- Part B (pm_plate_lookup + tag_mismatch/tag_voided) is a separate
-- file and waits on the capture of the live function body.

-- ── the table ───────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.vehicle_parking_tags (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_id    BIGINT      NOT NULL REFERENCES public.vehicles(id)   ON DELETE CASCADE,
  property_id   BIGINT      NOT NULL REFERENCES public.properties(id) ON DELETE RESTRICT,
  tag_number    TEXT        NOT NULL,
  assigned_by   TEXT        NOT NULL,
  assigned_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  voided_at     TIMESTAMPTZ,
  voided_by     TEXT,
  voided_reason TEXT,
  voided_note   TEXT,
  CONSTRAINT vehicle_parking_tags_number_not_blank
    CHECK (tag_number <> '' AND tag_number = upper(tag_number)),
  -- A void is all-or-nothing: a row cannot carry a voided_at without a
  -- reason, nor a reason without the timestamp that makes it true.
  CONSTRAINT vehicle_parking_tags_void_is_complete
    CHECK ((voided_at IS NULL     AND voided_by IS NULL     AND voided_reason IS NULL)
        OR (voided_at IS NOT NULL AND voided_by IS NOT NULL AND voided_reason IS NOT NULL))
);

COMMENT ON TABLE public.vehicle_parking_tags IS
  'Physical parking tag (hangtag/decal) numbers recorded against a vehicle, per property. NOT permits — permits are the billing meter. The plate remains the source of truth; a tag corroborates it and lets enforcement detect a tag hanging in the wrong car (tag_mismatch) or one that was collected (tag_voided). Written ONLY by set_vehicle_tag / void_vehicle_tag: there is deliberately no INSERT/UPDATE/DELETE policy, because manager_update_vehicles would otherwise have made a column on vehicles directly manager-writable. Voided rows are retained, never deleted, so a scan of an old tag can still be told apart from one that never existed.';

-- 🔴 One LIVE tag per number per property. Voided rows excluded, so a
-- collected tag number can be re-issued to a different vehicle later —
-- which is the whole point of voiding instead of deleting.
CREATE UNIQUE INDEX IF NOT EXISTS vehicle_parking_tags_one_live_per_property
  ON public.vehicle_parking_tags (property_id, tag_number)
  WHERE voided_at IS NULL;

-- 🔴 One LIVE tag per vehicle. Re-issuing voids the previous row first
-- (set_vehicle_tag does this in one statement-pair), so this is the
-- invariant that makes "the vehicle's current tag" a single row rather
-- than a max(assigned_at) guess.
CREATE UNIQUE INDEX IF NOT EXISTS vehicle_parking_tags_one_live_per_vehicle
  ON public.vehicle_parking_tags (vehicle_id)
  WHERE voided_at IS NULL;

CREATE INDEX IF NOT EXISTS vehicle_parking_tags_lookup
  ON public.vehicle_parking_tags (property_id, tag_number, voided_at);

