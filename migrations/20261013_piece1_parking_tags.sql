-- ── normalization ───────────────────────────────────────────────────
-- IMMUTABLE so it can be used in an index or a generated column later.
-- Same aggressive strip as plates: a physical tag reading "A-1024" and
-- one reading "A 1024" are the same object, and two residents must not
-- both hold "it" because one was written with a hyphen.
CREATE OR REPLACE FUNCTION public.normalize_tag_number(p TEXT)
RETURNS TEXT
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = public, pg_temp
AS $fn$
  SELECT NULLIF(regexp_replace(upper(COALESCE(p, '')), '[^A-Z0-9]', '', 'g'), '')
$fn$;

COMMENT ON FUNCTION public.normalize_tag_number(TEXT) IS
  'Uppercase, strip every non-alphanumeric, empty string to NULL. Mirrors the plate normalizer: "A-1024", "a 1024" and "A1024" are one physical tag, and allowing all three to be live at one property would let two vehicles each believe they hold it. Returns NULL for blank input so a caller can clear a tag by passing an empty string.';

