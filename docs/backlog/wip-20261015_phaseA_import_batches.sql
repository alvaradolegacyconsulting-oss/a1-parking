-- PHASE A — import_batches, the batch stamp, and the private bucket
-- ════════════════════════════════════════════════════════════════════
--
-- 🔴 WRITER SWEEP FIRST (ruled, binding). 41 existing write sites on
-- the two tables the new column touches:
--     residents  21 sites — 18 client, 3 service
--     vehicles   20 sites — 15 client,  5 service
-- plus manager_add_vehicle. NONE of them sets import_batch_id, which is
-- why the column is NULLABLE and why the guard below is written to be
-- INERT for every one of them.
--
-- Planned writers of import_batches, enumerated before the policies:
--     CA page            SELECT own company          → policy
--     super-admin queue  SELECT all                  → policy
--     submission         INSERT                      → SERVER ROUTE
--     approve / reject   UPDATE status               → RPC (Phase B)
--     loader             UPDATE status='loaded'      → RPC (Phase B)
--     rollback           UPDATE status='rolled_back' → RPC (Phase B)
-- So: TWO SELECT policies, and NO INSERT OR UPDATE POLICY AT ALL.
-- There is no legitimate client write, so omitting the policies costs
-- nothing and a forgotten one cannot become a path.
--
-- 🔴 NO CLIENT INSERT (ruled). A client insert would mean the client
-- supplies file_sha256 and the attestation fields, which breaks the
-- rule that the hash is computed server-side on the received bytes.
--
-- 🔴 AND IT CANNOT BE A DEFINER RPC EITHER — a correction to the
-- ruling's wording, forced by how storage works. Supabase keeps object
-- METADATA in storage.objects and the BYTES in S3; a storage row
-- carries only (name, version, id, timestamps, metadata). No SQL
-- function can read the content, and digest() is not exposed. So
-- submission is a Next.js server route on service_role that reads the
-- object, hashes it in Node, and inserts. Mirrors the shape already
-- used for property-authorizations: client uploads, a server route
-- handles the privileged half.
--
-- Paired: wip-20261015_phaseA_import_batches_verification.sql
-- Execution half: npm run verify:importbatches

-- ── 1. the table ────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS public.import_batches (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id          BIGINT      NOT NULL REFERENCES public.companies(id)  ON DELETE RESTRICT,
  property_id         BIGINT      NOT NULL REFERENCES public.properties(id) ON DELETE RESTRICT,
  source_filename     TEXT        NOT NULL,
  storage_path        TEXT        NOT NULL,
  -- Computed server-side on the received bytes. 64 hex chars.
  file_sha256         TEXT        NOT NULL,
  attested_by_user_id UUID        NOT NULL,
  attested_name       TEXT        NOT NULL,
  attested_title      TEXT        NOT NULL,
  attested_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  status              TEXT        NOT NULL DEFAULT 'submitted',
  reject_reason       TEXT,
  approved_by         TEXT,
  approved_at         TIMESTAMPTZ,
  resident_count      INT         NOT NULL,
  vehicle_count       INT         NOT NULL,
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT import_batches_status_allowed
    CHECK (status IN ('submitted', 'rejected', 'loaded', 'rolled_back')),
  -- An allowlist, not a denylist: an unknown status must fail closed.
  CONSTRAINT import_batches_sha256_shape
    CHECK (file_sha256 ~ '^[0-9a-f]{64}$'),
  -- A rejection without a reason is not a rejection the CA can act on.
  CONSTRAINT import_batches_reject_has_reason
    CHECK (status <> 'rejected' OR COALESCE(btrim(reject_reason), '') <> ''),
  -- Approval and load must name who and when.
  CONSTRAINT import_batches_approval_complete
    CHECK (status NOT IN ('loaded', 'rolled_back')
           OR (approved_by IS NOT NULL AND approved_at IS NOT NULL)),
  CONSTRAINT import_batches_counts_nonneg
    CHECK (resident_count >= 0 AND vehicle_count >= 0),
  -- 🔴 The same bytes must not be loaded twice under one property. The
  -- hash is the identity of the file, so this is the duplicate-submit
  -- guard, scoped to live batches only — a rejected file may be fixed
  -- and resubmitted, and a rolled-back one may be reloaded.
  CONSTRAINT import_batches_filename_not_blank
    CHECK (btrim(source_filename) <> '' AND btrim(storage_path) <> '')
);

CREATE UNIQUE INDEX IF NOT EXISTS import_batches_one_live_per_file
  ON public.import_batches (property_id, file_sha256)
  WHERE status IN ('submitted', 'loaded');

CREATE INDEX IF NOT EXISTS import_batches_queue
  ON public.import_batches (status, created_at DESC);

COMMENT ON TABLE public.import_batches IS
  'One row per customer-owned bulk onboarding submission. The CA uploads a CSV to the private bulk-onboarding bucket; a SERVER ROUTE then reads the object, computes file_sha256 on the received bytes, and inserts this row with attested_by_user_id = auth.uid() and company_id derived from the caller''s role — never from the payload. There is deliberately NO client INSERT or UPDATE policy: status transitions go through RPCs, so a forgotten policy cannot become a write path. Batch rows are AUDIT and are never deleted, which is why import_batch_id references them ON DELETE RESTRICT.';

-- ── 2. grants and RLS: read-only for clients ────────────────────────
REVOKE ALL ON public.import_batches FROM anon;
REVOKE ALL ON public.import_batches FROM authenticated;
GRANT SELECT ON public.import_batches TO authenticated;
-- No INSERT/UPDATE/DELETE grant: belt for the missing policies.

ALTER TABLE public.import_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.import_batches FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS ib_company_admin_select ON public.import_batches;
CREATE POLICY ib_company_admin_select ON public.import_batches
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.user_roles ur
              JOIN public.companies c ON c.id = import_batches.company_id
       WHERE lower(trim(ur.email)) = lower(trim(COALESCE(auth.jwt() ->> 'email', '')))
         AND ur.is_active
         AND ur.role = 'company_admin'
         AND lower(trim(ur.company)) = lower(trim(c.name))
    )
  );

DROP POLICY IF EXISTS ib_admin_select ON public.import_batches;
CREATE POLICY ib_admin_select ON public.import_batches
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM public.user_roles ur
       WHERE lower(trim(ur.email)) = lower(trim(COALESCE(auth.jwt() ->> 'email', '')))
         AND ur.is_active AND ur.role = 'admin'
    )
  );

-- ── 3. the batch stamp on the two data tables ───────────────────────
-- 🔴 NULLABLE, because 41 existing write sites do not supply it.
-- 🔴 ON DELETE RESTRICT: batch rows are audit and are never deleted.
-- SET NULL would either trip the write-once guard below or silently
-- detach rows from the batch that rollback needs to find them by.
ALTER TABLE public.residents
  ADD COLUMN IF NOT EXISTS import_batch_id BIGINT
  REFERENCES public.import_batches(id) ON DELETE RESTRICT;
ALTER TABLE public.vehicles
  ADD COLUMN IF NOT EXISTS import_batch_id BIGINT
  REFERENCES public.import_batches(id) ON DELETE RESTRICT;

CREATE INDEX IF NOT EXISTS residents_import_batch_id_idx ON public.residents (import_batch_id) WHERE import_batch_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS vehicles_import_batch_id_idx  ON public.vehicles  (import_batch_id) WHERE import_batch_id IS NOT NULL;

COMMENT ON COLUMN public.vehicles.import_batch_id IS
  'The bulk-onboarding batch that created this row, or NULL for every other path. 🔴 LOADER-ONLY AND WRITE-ONCE, enforced by import_batch_write_once_guard: rollback correctness depends on this column being truthful, and managers hold UPDATE on vehicles, so a direct PATCH could otherwise forge an association (making a row deletable by a batch it never belonged to) or clear one (making rollback miss it).';

-- ── 4. the write-once guard ─────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.import_batch_write_once_guard()
RETURNS TRIGGER
LANGUAGE plpgsql
-- 🔴 NOT SECURITY DEFINER: current_user is the discriminator, and
-- inside a DEFINER function it would read the OWNER for every caller.
SET search_path = public, pg_temp
AS $fn$
BEGIN
  -- 🔴 INERT FOR EVERY EXISTING WRITER. This trigger sits on two tables
  -- with 41 write sites between them, none of which touches this
  -- column. It returns immediately unless the column is ACTUALLY being
  -- written, so a manager add, a resident registration, a CA edit, a
  -- decline, a reactivation and the B113 service-role insert all pass
  -- through without evaluating another line.
  IF TG_OP = 'INSERT' THEN
    IF NEW.import_batch_id IS NULL THEN RETURN NEW; END IF;
  ELSE
    IF OLD.import_batch_id IS NOT DISTINCT FROM NEW.import_batch_id THEN RETURN NEW; END IF;
  END IF;

  -- Beyond here the column is genuinely changing.

  -- (a) A client may never write it, however privileged.
  IF current_user = 'authenticated' THEN
    RAISE EXCEPTION 'import_batch_id_not_writable'
      USING HINT = 'import_batch_id is set only by the bulk-onboarding loader. Rollback relies on it being accurate, so it cannot be written from a client session.';
  END IF;

  -- (b) Write-once, for EVERY caller including service_role. Rollback
  -- deletes rows rather than re-pointing them, so a non-NULL value
  -- never legitimately changes. Re-pointing a loaded row at another
  -- batch would make rollback destroy the wrong data.
  IF TG_OP = 'UPDATE' AND OLD.import_batch_id IS NOT NULL THEN
    RAISE EXCEPTION 'import_batch_id_already_set'
      USING HINT = format('This row already belongs to batch %s. A batch stamp is write-once: rollback deletes by it, so re-pointing a row would make rollback destroy the wrong data.', OLD.import_batch_id);
  END IF;

  RETURN NEW;
END;
$fn$;

REVOKE ALL ON FUNCTION public.import_batch_write_once_guard() FROM PUBLIC;
REVOKE ALL ON FUNCTION public.import_batch_write_once_guard() FROM anon;
REVOKE ALL ON FUNCTION public.import_batch_write_once_guard() FROM authenticated;

COMMENT ON FUNCTION public.import_batch_write_once_guard() IS
  'Keeps residents.import_batch_id and vehicles.import_batch_id loader-only and write-once. 🔴 Deliberately INERT unless the column is actually being written — it sits on two tables with 41 existing write sites, none of which touches it, and the gate proves all six representative paths still pass. Refuses an `authenticated` write outright (current_user, not auth.jwt(), so DEFINER RPCs are exempt by what they are) and refuses ANY change to a non-NULL value including from service_role, because rollback deletes by this column and re-pointing a row would make it destroy the wrong data.';

DROP TRIGGER IF EXISTS residents_import_batch_write_once ON public.residents;
CREATE TRIGGER residents_import_batch_write_once
  BEFORE INSERT OR UPDATE OF import_batch_id ON public.residents
  FOR EACH ROW EXECUTE FUNCTION public.import_batch_write_once_guard();

DROP TRIGGER IF EXISTS vehicles_import_batch_write_once ON public.vehicles;
CREATE TRIGGER vehicles_import_batch_write_once
  BEFORE INSERT OR UPDATE OF import_batch_id ON public.vehicles
  FOR EACH ROW EXECUTE FUNCTION public.import_batch_write_once_guard();
